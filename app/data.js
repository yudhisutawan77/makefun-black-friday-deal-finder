export const categories = [...new Set(deals.map((d) => d.category))].sort();
export const stores = [...new Set(deals.map((d) => d.store))].sort();

export function discountPercent(deal) {
  return Math.round((1 - deal.price / deal.was) * 100);
}

export function dollarsSaved(deal) {
  return deal.was - deal.price;
}

// Cheapest listing of a product across this board and its compare rows.
export function bestPriceFor(deal) {
  const all = [{ store: deal.store, price: deal.price }, ...deal.compare];
  return all.reduce((best, row) => (row.price < best.price ? row : best), all[0]);
}

export function isBestPrice(deal) {
  return bestPriceFor(deal).store === deal.store;
}
